// A variable is not tied to one type: the same variable holds a string, then a number,
// then a boolean.
let c = 'JavaScript';
console.log(c); // JavaScript
console.log(typeof c); // string

c = 6;
console.log(c); // 6
console.log(typeof c); // number

c = true;
console.log(c); // true
console.log(typeof c); // boolean
