var var1 = 3;
var var2 = 4;

// Greater than
console.log(var2 > var1); // true
console.log('12' > 2); // true

// Greater than or equal
console.log(var2 >= var1); // true
console.log(var1 >= 3); // true

// Less than
console.log(var1 < var2); // true
console.log('2' < 12); // true

// Less than or equal
console.log(var1 <= var2); // true
console.log(var2 <= 5); // true
