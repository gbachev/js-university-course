// 13 is 1101 and 9 is 1001 in binary.
console.log(13 & 9); // 9, 1101 & 1001 = 1001
console.log(13 | 9); // 13, 1101 | 1001 = 1101
console.log(13 ^ 9); // 4, 1101 ^ 1001 = 0100
console.log(~13); // -14, 0000 0000 ... 0000 1101 => 1111 1111 ... 1111 0010
console.log(~9); // -10, 0000 0000 ... 0000 1001 => 1111 1111 ... 1111 0110
