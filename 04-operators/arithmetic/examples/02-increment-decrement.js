let x = 3;

// Prefix: add one first, then return the new value.
console.log(++x); // 4
console.log(x); // 4

// Postfix: return the value first, then add one.
x = 3;
console.log(x++); // 3
console.log(x); // 4

// The decrement operator works the same way.
x = 3;
console.log(--x); // 2

x = 3;
console.log(x--); // 3
console.log(x); // 2
