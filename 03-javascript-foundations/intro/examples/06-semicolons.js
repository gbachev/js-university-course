// With each statement on its own line, the semicolons are optional.
let a = 1;
let b = 2;
console.log(a + b); // 3

let c = 3
let d = 4
console.log(c + d) // 7

// On one line, they are not. Remove the semicolons from the next line
// and the whole file stops with a SyntaxError before anything runs.
let e = 5; let f = 6; console.log(e + f); // 11
